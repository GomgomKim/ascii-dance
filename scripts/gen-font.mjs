// Dev-only: rasterize a monospace font into 8-bit alpha masks used by `--export`.
// Run: node scripts/gen-font.mjs  (requires playwright + chromium + JetBrains Mono installed)
// Output: src/core/font-data.ts
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
import { writeFileSync } from 'node:fs';

const CELL_W = 12;
const CELL_H = 24;
const FONT_PX = 20;

let chars = '';
for (let c = 32; c <= 126; c++) chars += String.fromCharCode(c);
chars += '░▒▓█▀▄▌▐■●○◆◇★☆♥♪♫·•';

const browser = await chromium.launch();
const page = await browser.newPage();
const result = await page.evaluate(
  ({ chars, CELL_W, CELL_H, FONT_PX }) => {
    const canvas = document.createElement('canvas');
    canvas.width = CELL_W;
    canvas.height = CELL_H;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    const out = {};
    for (const ch of chars) {
      ctx.fillStyle = '#000';
      ctx.fillRect(0, 0, CELL_W, CELL_H);
      ctx.fillStyle = '#fff';
      ctx.font = `${FONT_PX}px "JetBrains Mono", "DejaVu Sans Mono", monospace`;
      ctx.textBaseline = 'middle';
      ctx.textAlign = 'center';
      ctx.fillText(ch, CELL_W / 2, CELL_H / 2 + 1);
      const data = ctx.getImageData(0, 0, CELL_W, CELL_H).data;
      const mask = [];
      for (let i = 0; i < data.length; i += 4) mask.push(data[i]);
      out[ch] = mask;
    }
    return out;
  },
  { chars, CELL_W, CELL_H, FONT_PX },
);
await browser.close();

// Block elements are drawn procedurally so they tile seamlessly between cells.
const proc = (fn) => {
  const mask = [];
  for (let y = 0; y < CELL_H; y++) for (let x = 0; x < CELL_W; x++) mask.push(fn(x, y));
  return mask;
};
// Shades use an ordered-dither pattern so they read like real terminal shading.
const bayer = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5],
];
const shade = (level) => (x, y) => (bayer[(y >> 1) % 4][(x >> 1) % 4] < level * 16 ? 255 : 0);
result['░'] = proc(shade(0.25));
result['▒'] = proc(shade(0.5));
result['▓'] = proc(shade(0.75));
result['█'] = proc(() => 255);
result['▀'] = proc((x, y) => (y < CELL_H / 2 ? 255 : 0));
result['▄'] = proc((x, y) => (y >= CELL_H / 2 ? 255 : 0));
result['▌'] = proc((x) => (x < CELL_W / 2 ? 255 : 0));
result['▐'] = proc((x) => (x >= CELL_W / 2 ? 255 : 0));

const entries = Object.entries(result).map(
  ([ch, mask]) => `  ${JSON.stringify(ch)}: ${JSON.stringify(Buffer.from(mask).toString('base64'))},`,
);
const src = `// AUTO-GENERATED by scripts/gen-font.mjs — do not edit.
// Glyphs rasterized from JetBrains Mono (SIL Open Font License 1.1).
export const GLYPH_W = ${CELL_W};
export const GLYPH_H = ${CELL_H};
/** base64-encoded 8-bit alpha masks, GLYPH_W * GLYPH_H bytes each */
export const GLYPHS: Record<string, string> = {
${entries.join('\n')}
};
`;
writeFileSync(new URL('../src/core/font-data.ts', import.meta.url), src);
console.log(`wrote ${Object.keys(result).length} glyphs`);
